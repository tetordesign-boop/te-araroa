const dicts: Record<Lang, Dict> = { fr, en };
export type Key = keyof Dict;

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "fr" || saved === "en") return saved;
  } catch (_) { /* storage unavailable */ }
  const nav = (navigator.languages?.[0] ?? navigator.language ?? "fr").toLowerCase();
  return nav.startsWith("fr") ? "fr" : "en";
}

export const lang = signal<Lang>(initialLang());
export const hikerName = signal<string>("Ewan");

export function setLang(l: Lang) {
  lang.value = l;
  document.documentElement.lang = l;
  try { localStorage.setItem("lang", l); } catch (_) { /* ignore */ }
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  let s: string = dicts[lang.value][key] ?? dicts.fr[key] ?? key;
  const name = hikerName.value || "Ewan";
  s = s.replace(/Ewan/g, name);
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  s = s.replace("{name}", name);
  // a number never leaves its unit at the end of a line ("12 km", "1 310 m")
  s = s.replace(/(\d) (?=(km|m|h|min)\b)/g, "$1\u00a0");
  // French typography: a narrow no-break space before ? ! : ; and inside « », so no sign is left alone on a line
  if (lang.value === "fr") s = s.replace(/[ \u00a0]+([?!:;»])/g, "\u202f$1").replace(/«[ \u00a0]+/g, "«\u202f");
  return s;
}

/** WMO weather codes → short label. */
export function weatherLabel(code: number, l: Lang): { label: string; icon: string } {
  const table: [number[], string, string, string][] = [
    [[0], "ciel dégagé", "clear sky", "☀️"],
    [[1], "plutôt dégagé", "mostly clear", "🌤️"],
    [[2], "partiellement nuageux", "partly cloudy", "⛅"],
    [[3], "couvert", "overcast", "☁️"],
    [[45, 48], "brouillard", "fog", "🌫️"],
    [[51, 53, 55, 56, 57], "bruine", "drizzle", "🌦️"],
    [[61, 63, 66, 80, 81], "pluie", "rain", "🌧️"],
    [[65, 67, 82], "forte pluie", "heavy rain", "🌧️"],
    [[71, 73, 75, 77, 85, 86], "neige", "snow", "🌨️"],
    [[95, 96, 99], "orage", "thunderstorm", "⛈️"],
  ];
  for (const [codes, f, e, icon] of table) if (codes.includes(code)) return { label: l === "fr" ? f : e, icon };
  return { label: "", icon: "🌡️" };
}
